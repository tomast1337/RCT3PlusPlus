    template<std::size_t N> std::vector<std::byte> bytes(const std::array<std::uint8_t, N>& values)
    {
        std::vector<std::byte> out;
        for (const std::uint8_t v : values)
            out.push_back(static_cast<std::byte>(v));
        return out;
    }

